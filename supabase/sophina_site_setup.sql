-- Sophina website: news, photo albums, staff (filled by the Telegram bot).
-- Run this ONCE in the Supabase SQL editor.

create table if not exists site_news (id bigint generated always as identity primary key, title text not null, body text not null default '', image_url text, posted_at timestamptz not null default now(), active boolean not null default true);
create table if not exists site_photos (id bigint generated always as identity primary key, album text not null, image_url text not null, caption text, active boolean not null default true, created_at timestamptz not null default now());
create index if not exists site_photos_album_idx on site_photos (album);
create table if not exists site_staff (id bigint generated always as identity primary key, name text not null, position text not null default '', image_url text, sort_order int not null default 1000, active boolean not null default true, created_at timestamptz not null default now());
create table if not exists site_bot_state (chat_id bigint primary key, album text, updated_at timestamptz not null default now());

alter table site_news enable row level security;
alter table site_photos enable row level security;
alter table site_staff enable row level security;
alter table site_bot_state enable row level security;
drop policy if exists "public read news" on site_news;
create policy "public read news" on site_news for select using (active);
drop policy if exists "public read photos" on site_photos;
create policy "public read photos" on site_photos for select using (active);
drop policy if exists "public read staff" on site_staff;
create policy "public read staff" on site_staff for select using (active);
-- (site_bot_state has no public policy: only the bot, using the service key, can use it)

